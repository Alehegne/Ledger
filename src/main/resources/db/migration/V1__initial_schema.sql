CREATE TABLE organization (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    name VARCHAR(150) NOT NULL,
    base_currency VARCHAR(3) NOT NULL,
    created_at TIMESTAMPTZ NOT NULL,
    updated_at TIMESTAMPTZ NOT NULL
);

CREATE TABLE app_user (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    organization_id BIGINT NOT NULL,
    email VARCHAR(255) NOT NULL,
    password_hash VARCHAR(255) NOT NULL,
    full_name VARCHAR(150) NOT NULL,
    role VARCHAR(20) NOT NULL,
    created_at TIMESTAMPTZ NOT NULL,
    updated_at TIMESTAMPTZ NOT NULL,
    CONSTRAINT fk_app_user_organization FOREIGN KEY (organization_id) REFERENCES organization(id),
    CONSTRAINT uk_app_user_org_email UNIQUE (organization_id, email),
    CONSTRAINT chk_app_user_role CHECK (role IN ('ADMIN', 'ACCOUNTANT', 'VIEWER'))
);

CREATE TABLE account (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    organization_id BIGINT NOT NULL,
    parent_account_id BIGINT,
    account_code VARCHAR(50) NOT NULL,
    name VARCHAR(150) NOT NULL,
    account_type VARCHAR(20) NOT NULL,
    status VARCHAR(20) NOT NULL,
    created_at TIMESTAMPTZ NOT NULL,
    updated_at TIMESTAMPTZ NOT NULL,
    CONSTRAINT fk_account_organization FOREIGN KEY (organization_id) REFERENCES organization(id),
    CONSTRAINT fk_account_parent FOREIGN KEY (parent_account_id) REFERENCES account(id),
    CONSTRAINT uk_account_org_code UNIQUE (organization_id, account_code),
    CONSTRAINT chk_account_type CHECK (account_type IN ('ASSET', 'LIABILITY', 'EQUITY', 'REVENUE', 'EXPENSE')),
    CONSTRAINT chk_account_status CHECK (status IN ('ACTIVE', 'INACTIVE'))
);

CREATE TABLE journal_entry (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    organization_id BIGINT NOT NULL,
    transaction_date DATE NOT NULL,
    description VARCHAR(500) NOT NULL,
    reference VARCHAR(120),
    status VARCHAR(20) NOT NULL,
    created_by_user_id BIGINT NOT NULL,
    posted_by_user_id BIGINT,
    posted_at TIMESTAMPTZ,
    created_at TIMESTAMPTZ NOT NULL,
    updated_at TIMESTAMPTZ NOT NULL,
    CONSTRAINT fk_journal_entry_organization FOREIGN KEY (organization_id) REFERENCES organization(id),
    CONSTRAINT fk_journal_entry_created_by FOREIGN KEY (created_by_user_id) REFERENCES app_user(id),
    CONSTRAINT fk_journal_entry_posted_by FOREIGN KEY (posted_by_user_id) REFERENCES app_user(id),
    CONSTRAINT chk_journal_entry_status CHECK (status IN ('DRAFT', 'POSTED'))
);

CREATE TABLE journal_line (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    journal_entry_id BIGINT NOT NULL,
    account_id BIGINT NOT NULL,
    side VARCHAR(10) NOT NULL,
    amount NUMERIC(19,4) NOT NULL,
    created_at TIMESTAMPTZ NOT NULL,
    updated_at TIMESTAMPTZ NOT NULL,
    CONSTRAINT fk_journal_line_entry FOREIGN KEY (journal_entry_id) REFERENCES journal_entry(id) ON DELETE CASCADE,
    CONSTRAINT fk_journal_line_account FOREIGN KEY (account_id) REFERENCES account(id),
    CONSTRAINT chk_journal_line_side CHECK (side IN ('DEBIT', 'CREDIT')),
    CONSTRAINT chk_journal_line_amount_positive CHECK (amount > 0)
);

CREATE TABLE audit_log (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    organization_id BIGINT NOT NULL,
    actor_user_id BIGINT,
    action VARCHAR(100) NOT NULL,
    entity_type VARCHAR(100) NOT NULL,
    entity_id VARCHAR(100) NOT NULL,
    metadata_json TEXT,
    created_at TIMESTAMPTZ NOT NULL,
    updated_at TIMESTAMPTZ NOT NULL,
    CONSTRAINT fk_audit_log_organization FOREIGN KEY (organization_id) REFERENCES organization(id),
    CONSTRAINT fk_audit_log_actor FOREIGN KEY (actor_user_id) REFERENCES app_user(id)
);

CREATE TABLE invitation (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    organization_id BIGINT NOT NULL,
    invited_by_user_id BIGINT NOT NULL,
    invited_email VARCHAR(255) NOT NULL,
    role VARCHAR(20) NOT NULL,
    invitation_token VARCHAR(255) NOT NULL,
    expires_at TIMESTAMPTZ NOT NULL,
    accepted_at TIMESTAMPTZ,
    created_at TIMESTAMPTZ NOT NULL,
    updated_at TIMESTAMPTZ NOT NULL,
    CONSTRAINT fk_invitation_organization FOREIGN KEY (organization_id) REFERENCES organization(id),
    CONSTRAINT fk_invitation_invited_by FOREIGN KEY (invited_by_user_id) REFERENCES app_user(id),
    CONSTRAINT uk_invitation_token UNIQUE (invitation_token),
    CONSTRAINT chk_invitation_role CHECK (role IN ('ADMIN', 'ACCOUNTANT', 'VIEWER'))
);

CREATE INDEX idx_app_user_org ON app_user(organization_id);
CREATE INDEX idx_account_org ON account(organization_id);
CREATE INDEX idx_journal_entry_org ON journal_entry(organization_id);
CREATE INDEX idx_journal_line_entry ON journal_line(journal_entry_id);
CREATE INDEX idx_journal_line_account ON journal_line(account_id);
CREATE INDEX idx_audit_log_org ON audit_log(organization_id);
CREATE INDEX idx_invitation_org ON invitation(organization_id);