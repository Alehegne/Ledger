CREATE TABLE reconciliation_run (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    organization_id BIGINT NOT NULL,
    triggered_by_user_id BIGINT,
    status VARCHAR(20) NOT NULL,
    total_posted_debits NUMERIC(19, 4) NOT NULL,
    total_posted_credits NUMERIC(19, 4) NOT NULL,
    global_variance NUMERIC(19, 4) NOT NULL,
    posted_entry_count BIGINT NOT NULL,
    account_count BIGINT NOT NULL,
    checks_passed INTEGER NOT NULL,
    checks_failed INTEGER NOT NULL,
    checks_json TEXT NOT NULL,
    version BIGINT NOT NULL DEFAULT 0,
    created_at TIMESTAMPTZ NOT NULL,
    updated_at TIMESTAMPTZ NOT NULL,
    CONSTRAINT fk_reconciliation_run_organization FOREIGN KEY (organization_id) REFERENCES organization(id),
    CONSTRAINT fk_reconciliation_run_user FOREIGN KEY (triggered_by_user_id) REFERENCES app_user(id),
    CONSTRAINT chk_reconciliation_status CHECK (status IN ('PASSED', 'FAILED'))
);

CREATE INDEX idx_reconciliation_org_created ON reconciliation_run(organization_id, created_at DESC, id DESC);
